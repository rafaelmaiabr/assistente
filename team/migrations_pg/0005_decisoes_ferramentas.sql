CREATE TABLE tool_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  run_id TEXT NOT NULL,
  agent_id TEXT NOT NULL,
  agent_version BIGINT NOT NULL,
  tool TEXT NOT NULL,
  operation TEXT,
  decision TEXT NOT NULL CHECK (decision IN ('allowed', 'denied', 'error')),
  reason TEXT NOT NULL,
  policy_version TEXT NOT NULL,
  result_bytes BIGINT,
  duration_ms BIGINT,
  created_at TEXT NOT NULL,
  FOREIGN KEY (tenant_id, run_id) REFERENCES agent_runs(tenant_id, id)
);
CREATE INDEX tool_decisions_by_run ON tool_decisions (tenant_id, run_id, id);
